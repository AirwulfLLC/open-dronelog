/** Save binary/text content via Tauri dialog (desktop) or browser download. */
export async function saveReportFile(
  defaultName: string,
  content: Uint8Array | string,
  filterName: string,
  extension: string,
): Promise<boolean> {
  const isWeb = import.meta.env.VITE_BACKEND === 'web';
  if (!isWeb) {
    try {
      const { save } = await import('@tauri-apps/plugin-dialog');
      const path = await save({
        defaultPath: defaultName,
        filters: [{ name: filterName, extensions: [extension] }],
      });
      if (!path) return false;
      const fs = await import('@tauri-apps/plugin-fs');
      if (typeof content === 'string') {
        await fs.writeTextFile(path, content);
      } else {
        await fs.writeFile(path, content);
      }
      return true;
    } catch (e) {
      console.error('Tauri save failed, falling back to browser download:', e);
    }
  }
  // Browser fallback
  const blob =
    typeof content === 'string'
      ? new Blob([content], { type: 'application/rtf' })
      : new Blob([content as BlobPart], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = defaultName;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 5000);
  return true;
}
