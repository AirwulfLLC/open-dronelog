/**
 * Pieces shared by every report kind: value formatting, the sections both
 * kinds contain (header data, flight operations, orthomosaic, imagery
 * figures) written against the ReportWriter interface, and the save helper.
 *
 * A section lives here once it is used by more than one report kind;
 * kind-specific sections stay in that kind's module.
 */

import type { FlightSnapshot, PhotogrammetryEntry, ReportBase } from '@/types/thermal';
import type { PhotogrammetryFigure } from '@/lib/photogrammetryExport';
import type { EditRef, ReportWriter } from './writer';

// ---------------------------------------------------------------------------
// Formatting
// ---------------------------------------------------------------------------

export const SEVERITY_LABELS: Record<string, string> = {
  low: 'Low',
  medium: 'Medium',
  high: 'High',
};

export function fmtDuration(secs: number | null): string {
  if (secs == null || Number.isNaN(secs)) return '—';
  const total = Math.round(secs);
  const m = Math.floor(total / 60);
  const s = total % 60;
  return m > 0 ? `${m}m ${s}s` : `${s}s`;
}

export function fmtMeters(m: number | null): string {
  if (m == null || Number.isNaN(m)) return '—';
  return m >= 1000 ? `${(m / 1000).toFixed(2)} km` : `${m.toFixed(0)} m`;
}

export function fmtTemp(t: number | null): string {
  return t == null || Number.isNaN(t) ? '—' : `${t.toFixed(1)} °C`;
}

export function fmtGps(lat: number | null, lon: number | null): string {
  if (lat == null || lon == null) return '—';
  return `${lat.toFixed(6)}, ${lon.toFixed(6)}`;
}

/** Publisher named under every report title. */
export const REPORT_PUBLISHER = 'Airwulf, LLC';

/** Provenance line under the title: publisher plus the workflow that produced the report. */
export function generatedBy(workflow: string): string {
  return `Generated by ${REPORT_PUBLISHER} · ${workflow}`;
}

/** Severity tally sentence used by both kinds' closing sections. */
export function prioritySummary(severities: string[]): string {
  const count = (s: string) => severities.filter((x) => x === s).length;
  return (
    `Priority summary: ${count('high')} high-severity (immediate corrective action), ` +
    `${count('medium')} medium-severity (schedule repair), ` +
    `${count('low')} low-severity (monitor).`
  );
}

/** Edit reference for a top-level or nested report field. */
export const edit = (path: string, single = false): EditRef => ({ path, single });

/** Edit reference for a per-picture note (routed to the asset, not the report). */
export const assetNoteEdit = (assetId: number): EditRef => ({ path: `assetNote.${assetId}` });

