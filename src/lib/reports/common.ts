// Shared section: linked DJI flights
// ---------------------------------------------------------------------------

function flightDetails(f: FlightSnapshot): string {
  return [
    f.startTime ? `Date: ${f.startTime}` : null,
    f.droneModel ? `Drone: ${f.droneModel}${f.aircraftName ? ` (${f.aircraftName})` : ''}` : null,
    `Duration: ${fmtDuration(f.durationSecs)}`,
    `Distance: ${fmtMeters(f.totalDistance)}`,
    f.maxAltitude != null ? `Max altitude: ${f.maxAltitude.toFixed(0)} m` : null,
    f.maxSpeed != null ? `Max speed: ${f.maxSpeed.toFixed(1)} m/s` : null,
    f.homeLat != null && f.homeLon != null ? `Home: ${f.homeLat.toFixed(6)}, ${f.homeLon.toFixed(6)}` : null,
    f.photoCount != null ? `Photos: ${f.photoCount}` : null,
  ]
    .filter(Boolean)
    .join('  ·  ');
}

export function flightOperations(w: ReportWriter, flights: FlightSnapshot[]): void {
  if (flights.length === 0) return;
  w.sectionHeading('Flight Operations (DJI)');
  for (const f of flights) {
    w.subheading(f.displayName || `Flight ${f.id}`);
    w.detail(flightDetails(f));
    w.space(3);
  }
}

